test('the preview is editable: what is created is what the student corrected', async ({ page }) => {
  const assertClean = watch(page);
  await newUser(page, ['Redes', 'Bases de Datos']);
  await interpret(page, `parcial redes ${tomorrowName} 10am`);
  const bases = (await subjects(page)).find((s) => s.name === 'Bases de Datos')!;
  const inTwoDays = bogotaToday(2);

  await preview(page).getByLabel('Título').fill('Quiz de repaso');
  await preview(page).getByLabel('Asignatura').selectOption({ label: 'Bases de Datos' });
  await preview(page).getByLabel('Tipo').selectOption({ label: 'Quiz' });
  await preview(page).getByLabel('Fecha').fill(inTwoDays);
  await preview(page).getByLabel('Hora (opcional)').fill('15:30');
  await create(page).click();
  await expect(capture(page).getByRole('status')).toContainText(
    'Actividad creada: Quiz de repaso.',
  );

  const [created] = await activities(page);
  expect(created).toMatchObject({
    title: 'Quiz de repaso',
    type: 'QUIZ',
    subjectId: bases.id,
    hasTime: true,
  });
  // 15:30 on the chosen day in Bogotá (UTC-5) is 20:30 UTC.
  expect(created!.dueAt).toBe(`${inTwoDays}T20:30:00.000Z`);
  assertClean();
});

test('empty and too long input are explained before calling anything', async ({ page }) => {
  const assertClean = watch(page);
  await newUser(page);
  await page.goto('/dashboard');
  let calls = 0;
  page.on('request', (r) => {
    if (r.url().includes('/api/quick-capture/parse')) calls++;
  });

  await capture(page).getByRole('button', { name: 'Interpretar' }).click();
  await expect(capture(page).getByRole('alert')).toHaveText(
    'Escribe una actividad para continuar.',
  );
  await expect(textbox(page)).toHaveAttribute('aria-invalid', 'true');
  await textbox(page).fill('x'.repeat(301));
  await capture(page).getByRole('button', { name: 'Interpretar' }).click();
  await expect(capture(page).getByRole('alert')).toHaveText(
    'Este texto parece demasiado largo para Captura rápida.',
  );
  expect(calls).toBe(0);
  expect(await activities(page)).toHaveLength(0);
  assertClean();
});

test('if interpreting fails the text is kept and the manual form is one click away', async ({
  page,
}) => {
  await newUser(page);
  await page.goto('/dashboard');
  await page.route('**/api/quick-capture/parse', (route) =>
    route.fulfill({
      status: 500,
      contentType: 'application/json',
      body: JSON.stringify({ error: { code: 'INTERNAL_ERROR', message: 'boom' } }),
    }),
  );
  await textbox(page).fill(`parcial redes ${tomorrowName} 10am`);
  await capture(page).getByRole('button', { name: 'Interpretar' }).click();
  await expect(capture(page).getByRole('alert')).toContainText(
    'No pudimos interpretar el texto. Puedes intentarlo de nuevo o crear la actividad manualmente.',
  );
  await expect(textbox(page)).toHaveValue(`parcial redes ${tomorrowName} 10am`);
  await capture(page).getByRole('link', { name: 'Crear manualmente' }).click();
  await expect(page).toHaveURL(/\/activities/);
  await expect(page.getByRole('dialog', { name: 'Agregar actividad' })).toBeVisible();
  // (No console check here: a mocked 500 is logged by the browser on purpose.)
});

test('accessibility: a real label, keyboard, focus and warnings tied to the preview', async ({
  page,
}) => {
  const assertClean = watch(page);
  await newUser(page);
  await page.goto('/dashboard');
  await expect(page.getByLabel('Escribe la actividad en una frase')).toBeVisible();
  // Tab order: text box -> Interpretar.
  await textbox(page).focus();
  await page.keyboard.press('Tab');
  await expect(capture(page).getByRole('button', { name: 'Interpretar' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(capture(page).getByRole('alert')).toBeVisible();

  await textbox(page).fill('parcial mañana');
  await textbox(page).press('Enter');
  await expect(preview(page)).toBeFocused();
  const describedBy = await preview(page).getAttribute('aria-describedby');
  expect(describedBy).toBe('quick-capture-warnings');
  await expect(page.locator('#quick-capture-warnings')).toContainText(
    'No reconocí una asignatura.',
  );
  // Every control of the preview has a label.
  for (const label of ['Título', 'Asignatura', 'Tipo', 'Fecha', 'Hora (opcional)']) {
    await expect(preview(page).getByLabel(label)).toBeVisible();
  }
  // The Dashboard keeps its one h1 and h2 sections: the preview adds no headings.
  await expect(page.getByRole('heading', { level: 1 })).toHaveCount(1);
  expect(await preview(page).getByRole('heading').count()).toBe(0);
  assertClean();
});

test('layout: the input, the preview and the buttons fit the screen with a long phrase', async ({
  page,
}) => {
  const assertClean = watch(page);
  await newUser(page, [
    'Asignatura con un nombre bastante largo para comprobar el ajuste de línea',
  ]);
  const phrase = `parcial asignatura con un nombre bastante largo ${'tema'.repeat(10)} ${tomorrowName} 10am`;
  await page.goto('/dashboard');
  await textbox(page).fill(phrase);
  await expectNoHorizontalOverflow(page);
  const viewport = page.viewportSize()!;
  const box = (await textbox(page).boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0);
  expect(box.x + box.width).toBeLessThanOrEqual(viewport.width);
  await capture(page).getByRole('button', { name: 'Interpretar' }).click();
  await expect(preview(page)).toBeVisible();
  await expectNoHorizontalOverflow(page);
  for (const label of ['Título', 'Asignatura', 'Tipo', 'Fecha', 'Hora (opcional)']) {
    const b = (await preview(page).getByLabel(label).boundingBox())!;
    expect(b.x, label).toBeGreaterThanOrEqual(0);
    expect(b.x + b.width, label).toBeLessThanOrEqual(viewport.width);
  }
  for (const name of ['Crear actividad', 'Volver a editar texto', 'Cancelar']) {
    const b = (await preview(page).getByRole('button', { name }).boundingBox())!;
    expect(b.height, name).toBeGreaterThanOrEqual(44);
    expect(b.x + b.width, name).toBeLessThanOrEqual(viewport.width);
  }
  assertClean();
});

test('"hoy" is the profile’s day, not the browser’s', async ({ browser }) => {
  // The browser believes it is in Tokyo (UTC+9); the profile is Bogotá (UTC-5).
  const context = await browser.newContext({ timezoneId: 'Asia/Tokyo', locale: 'en-US' });
  const page = await context.newPage();
  const assertClean = watch(page);
  await newUser(page);
  await interpret(page, 'lectura redes hoy');
  await expect(preview(page).getByLabel('Fecha')).toHaveValue(bogotaToday());
  await expect(preview(page).getByLabel('Tipo')).toHaveValue('READING');
  assertClean();
  await context.close();
});
