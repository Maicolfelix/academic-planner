import { weekdayOf } from '@planner/core';
import { expect, test, type Page } from '@playwright/test';
import {
  addSubjectViaUi,
  bogotaToday,
  completeOnboarding,
  expectNoHorizontalOverflow,
  register,
  uniqueEmail,
  watch,
} from './helpers';

// A period that always contains "today" and the weeks around it (the system clock decides what today is).
const period = () => ({ start: bogotaToday(-70), end: bogotaToday(120) });
const nav = (page: Page) => page.getByRole('navigation', { name: 'Principal' });

/**
 * "mañana" as a weekday name. Typing tomorrow's weekday always resolves to tomorrow (never to today or to next
 * week), so the expected date does not depend on the time of day the test runs at.
 */
const TOMORROW = bogotaToday(1);
const DAY_NAMES = ['lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado', 'domingo'];
const tomorrowName = DAY_NAMES[weekdayOf(TOMORROW) - 1]!;

async function newUser(page: Page, subjects: string[] = ['Redes']) {
  await register(page, uniqueEmail());
  await completeOnboarding(page, 'Semestre de prueba', period());
  for (const name of subjects) await addSubjectViaUi(page, name);
}

const capture = (page: Page) => page.getByRole('region', { name: 'Captura rápida' });
const textbox = (page: Page) => capture(page).getByLabel('Escribe la actividad en una frase');
const preview = (page: Page) =>
  capture(page).getByRole('group', { name: 'Vista previa de la actividad' });
const create = (page: Page) => preview(page).getByRole('button', { name: 'Crear actividad' });

async function interpret(page: Page, text: string) {
  await page.goto('/dashboard');
  await textbox(page).fill(text);
  await capture(page).getByRole('button', { name: 'Interpretar' }).click();
  await expect(preview(page)).toBeVisible();
}

const activities = async (page: Page) =>
  (await (await page.request.get('/api/activities')).json()).activities as {
    id: string;
    title: string;
    type: string;
    subjectId: string;
    hasTime: boolean;
    dueAt: string;
    status: string;
  }[];
const subjects = async (page: Page) =>
  (await (await page.request.get('/api/subjects')).json()).subjects as {
    id: string;
    name: string;
  }[];

test('capture -> interpret -> confirm: the whole flow, down to reminders, Radar and Attention', async ({
  page,
}) => {
  const assertClean = watch(page);

  // 1-4. New user, current period, subject "Redes", Dashboard.
  await newUser(page);
  await page.goto('/dashboard');
  await expect(
    capture(page).getByRole('heading', { level: 2, name: 'Captura rápida' }),
  ).toBeVisible();
  await expect(textbox(page)).toHaveAttribute('placeholder', 'Ej: parcial redes martes 10am');

  // 5-6. Write the phrase and interpret it: Enter does NOT create anything.
  await textbox(page).fill(`parcial redes ${tomorrowName} 10am`);
  await textbox(page).press('Enter');
  await expect(preview(page)).toBeVisible();
  expect(await activities(page)).toHaveLength(0);

  // 7. The proposal: type, subject, date, time and title. Focus moves to it.
  await expect(preview(page)).toBeFocused();
  await expect(preview(page).getByLabel('Tipo')).toHaveValue('EXAM');
  await expect(preview(page).getByLabel('Asignatura')).toHaveValue((await subjects(page))[0]!.id);
  await expect(preview(page).getByLabel('Fecha')).toHaveValue(TOMORROW);
  await expect(preview(page).getByLabel('Hora (opcional)')).toHaveValue('10:00');
  await expect(preview(page).getByLabel('Título')).toHaveValue('Parcial');
  await expect(preview(page)).toContainText(
    /(Lunes|Martes|Miércoles|Jueves|Viernes|Sábado|Domingo) \d{1,2} de [a-záéíóú]+/,
  );
  await expect(preview(page)).toContainText('no se guarda nada hasta que pulses');
  await expectNoHorizontalOverflow(page);

  // 8-10. Edit the title and confirm: only now is it created.
  await preview(page).getByLabel('Título').fill('Parcial 1');
  await create(page).click();
  await expect(
    capture(page).getByRole('status').filter({ hasText: 'Actividad creada: Parcial 1.' }),
  ).toBeVisible();
  await expect(preview(page)).toHaveCount(0);
  await expect(textbox(page)).toHaveValue('');

  // 11-12. The activity exists, with the edited title, as an ordinary pending activity.
  const [created] = await activities(page);
  expect(created).toMatchObject({
    title: 'Parcial 1',
    type: 'EXAM',
    status: 'PENDING',
    hasTime: true,
  });
  await nav(page).getByRole('link', { name: 'Actividades' }).click();
  await expect(page.getByRole('listitem').filter({ hasText: 'Parcial 1' })).toBeVisible();

  // 13. Its automatic reminders were generated by the normal creation (3 h before tomorrow 10:00 is always ahead).
  await page.getByRole('button', { name: 'Editar Parcial 1', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Editar actividad' });
  await expect(
    edit
      .getByRole('region', { name: 'Recordatorios' })
      .getByRole('listitem')
      .filter({ hasText: 'Automático, 3 horas antes' }),
  ).toBeVisible();
  await edit.getByRole('button', { name: 'Cancelar' }).first().click();

  // 14-15. Back on the Dashboard it takes part in "¿Qué hago ahora?" and in the Radar, with no reload.
  await nav(page).getByRole('link', { name: 'Inicio' }).click();
  await expect(
    page
      .getByRole('region', { name: '¿Qué hago ahora?' })
      .getByRole('article', { name: 'Parcial 1' }),
  ).toBeVisible();
  await expect(page.getByRole('region', { name: 'Radar académico' })).toBeVisible();
  await page.goto('/radar');
  await expect(page.getByRole('listitem').filter({ hasText: 'Parcial 1' })).toBeVisible();

  // 16. No console errors, no uncaught exceptions and no failed API calls along the whole flow.
  assertClean();
});

test('without a time the activity has no time (hasTime false)', async ({ page }) => {
  const assertClean = watch(page);
  await newUser(page);
  await interpret(page, `tarea redes ${tomorrowName}`);
  await expect(preview(page).getByLabel('Tipo')).toHaveValue('TASK');
  await expect(preview(page).getByLabel('Fecha')).toHaveValue(TOMORROW);
  await expect(preview(page).getByLabel('Hora (opcional)')).toHaveValue('');
  await create(page).click();
  await expect(capture(page).getByRole('status')).toContainText('Actividad creada: Tarea.');
  const [created] = await activities(page);
  expect(created).toMatchObject({ title: 'Tarea', hasTime: false, type: 'TASK' });
  // No time: due at the end of the local day (23:59:59.999 in Bogotá is 04:59:59.999 UTC of the next day).
  expect(created!.dueAt.endsWith('T04:59:59.999Z')).toBe(true);
  assertClean();
});

test('an ambiguous subject asks which one: nothing is chosen for the student', async ({ page }) => {
  const assertClean = watch(page);
  await newUser(page, ['Programación I', 'Programación II']);
  await interpret(page, `parcial programacion ${tomorrowName}`);

  await expect(preview(page).getByText('Encontré más de una asignatura posible.')).toBeVisible();
  const choice = preview(page).getByRole('group', { name: '¿A cuál te refieres?' });
  await expect(choice.getByRole('radio')).toHaveCount(2);
  await expect(choice.getByRole('radio', { checked: true })).toHaveCount(0);
  await expect(preview(page).getByLabel('Asignatura')).toHaveValue('');
  await expect(create(page)).toBeDisabled();
  await expect(preview(page)).toContainText('Para crearla falta la asignatura.');

  // Operable with the keyboard.
  await choice.getByRole('radio', { name: 'Programación II' }).focus();
  await page.keyboard.press('Space');
  await expect(choice.getByRole('radio', { name: 'Programación II' })).toBeChecked();
  await expect(create(page)).toBeEnabled();
  await create(page).click();
  await expect(capture(page).getByRole('status')).toContainText('Actividad creada: Parcial.');
  const chosen = (await subjects(page)).find((s) => s.name === 'Programación II')!;
  expect((await activities(page))[0]!.subjectId).toBe(chosen.id);
  assertClean();
});

